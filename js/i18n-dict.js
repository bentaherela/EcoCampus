/* =====================================================================
   EcoCampus — Dictionnaire de traduction (français → anglais / arabe)

   Le français est la langue d'origine du site : chaque ligne est
       [ « texte français », « anglais », « arabe » ]

   • Un texte peut contenir des trous {0}, {1}… : ce sont les parties
     variables (nombres, noms de bâtiments, dates…). Elles sont
     recopiées telles quelles, ou traduites si elles figurent elles-mêmes
     dans le dictionnaire (ex. « Eau » → « Water »).
   • L'anglais ou l'arabe peut être une fonction (c) => texte quand il
     faut gérer le pluriel (voir arCount plus bas).
   • Pour traduire une nouvelle phrase : ajoutez simplement une ligne.
   ===================================================================== */

/* Pluriel arabe : 1 → singulier, 2 → duel, 3 à 10 → pluriel, 11 et + → singulier */
function arCount(raw, one, two, few, many) {
  const n = parseInt(String(raw).replace(/\D/g, ""), 10) || 0;
  if (n === 2) return two;
  if (n === 1 || n === 0) return `${raw} ${one}`;
  if (n >= 3 && n <= 10) return `${raw} ${few}`;
  return `${raw} ${many}`;
}

